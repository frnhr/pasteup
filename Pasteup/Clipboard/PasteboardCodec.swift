import AppKit
import ImageIO
import PasteupCore
import UniformTypeIdentifiers

/// A clip read from the clipboard, together with the data that goes to disk.
struct CapturedClip {
	var clip: Clip
	var items: [RawItem]
	var thumbnailPNG: Data?
}

/// Converts between `NSPasteboard` contents and clips.
enum PasteboardCodec {
	/// Markers that password managers and similar tools put on clipboard content that shouldn't be recorded.
	/// See https://nspasteboard.org
	static let ignoredTypes: Set<String> = [
		"org.nspasteboard.TransientType",
		"org.nspasteboard.ConcealedType",
		"org.nspasteboard.AutoGeneratedType",
		"com.agilebits.onepassword",
		"de.petermaurer.TransientPasteboardType",
		"com.typeit4me.clipping",
	]

	static let imageTypes: [NSPasteboard.PasteboardType] = [
		.png, .tiff, NSPasteboard.PasteboardType(UTType.jpeg.identifier), NSPasteboard.PasteboardType(UTType.heic.identifier),
	]

	static let thumbnailMaxPixels = 320

	/// Returns nil for an empty clipboard and for content marked as concealed or transient.
	static func capture(from pasteboard: NSPasteboard, date: Date) -> CapturedClip? {
		guard let pasteboardItems = pasteboard.pasteboardItems, !pasteboardItems.isEmpty else { return nil }
		let allTypes = pasteboardItems.flatMap { $0.types.map(\.rawValue) }
		guard Set(allTypes).isDisjoint(with: ignoredTypes) else { return nil }

		let items: [RawItem] = pasteboardItems
			.map { item in
				item.types.compactMap { type in
					item.data(forType: type).map { RawRepresentation(type: type.rawValue, data: $0) }
				}
			}
			.filter { !$0.isEmpty }
		guard !items.isEmpty else { return nil }

		let filePaths = pasteboardItems.compactMap { item -> String? in
			guard let string = item.string(forType: .fileURL), let url = URL(string: string), url.isFileURL else { return nil }
			return url.path
		}
		let text = plainText(from: pasteboard)
		let thumbnail = imageTypes.lazy.compactMap { pasteboard.data(forType: $0) }.first.flatMap(makeThumbnail)
		let color = NSColor(from: pasteboard).flatMap(rgba)

		let preview = ClipPreview(
			text: text.map(PreviewText.excerpt),
			filePaths: filePaths,
			imageSize: thumbnail?.size,
			color: color,
			types: uniqued(allTypes)
		)
		let searchText = filePaths.isEmpty
			? text.map(PreviewText.searchable) ?? ""
			: filePaths.map { ($0 as NSString).lastPathComponent }.joined(separator: "\n")

		let clip = Clip(
			capturedAt: date,
			contentHash: ContentHash.of(items),
			items: items.enumerated().map { itemIndex, item in
				ClipItem(representations: item.enumerated().map { representationIndex, representation in
					Representation(
						type: representation.type,
						blobName: "\(itemIndex)-\(representationIndex).bin",
						byteCount: representation.data.count
					)
				})
			},
			preview: preview,
			searchText: searchText,
			sourceApp: NSWorkspace.shared.frontmostApplication.map {
				SourceApp(bundleID: $0.bundleIdentifier, name: $0.localizedName)
			}
		)
		return CapturedClip(clip: clip, items: items, thumbnailPNG: thumbnail?.png)
	}

	/// The clip's text without formatting, or nil if it has none (e.g. an image).
	static func plainText(of clip: Clip, store: ClipStore) throws -> String? {
		let representations = clip.items.first?.representations ?? []
		if let stored = representations.first(where: { $0.type == NSPasteboard.PasteboardType.string.rawValue }) {
			return String(data: try store.readData(of: clip, representation: stored), encoding: .utf8)
		}
		if let stored = representations.first(where: { $0.type == NSPasteboard.PasteboardType.rtf.rawValue }) {
			return NSAttributedString(rtf: try store.readData(of: clip, representation: stored), documentAttributes: nil)?.string
		}
		return nil
	}

	private static func plainText(from pasteboard: NSPasteboard) -> String? {
		if let string = pasteboard.string(forType: .string) {
			return string
		}
		if let rtf = pasteboard.data(forType: .rtf) {
			return NSAttributedString(rtf: rtf, documentAttributes: nil)?.string
		}
		return nil
	}

	private static func makeThumbnail(from data: Data) -> (png: Data, size: PixelSize)? {
		guard let source = CGImageSourceCreateWithData(data as CFData, nil),
		      let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
		      let width = properties[kCGImagePropertyPixelWidth] as? Int,
		      let height = properties[kCGImagePropertyPixelHeight] as? Int
		else { return nil }

		let options: [CFString: Any] = [
			kCGImageSourceCreateThumbnailFromImageAlways: true,
			kCGImageSourceCreateThumbnailWithTransform: true,
			kCGImageSourceThumbnailMaxPixelSize: thumbnailMaxPixels,
		]
		guard let thumbnail = CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary) else { return nil }

		let output = NSMutableData()
		guard let destination = CGImageDestinationCreateWithData(output, UTType.png.identifier as CFString, 1, nil) else {
			return nil
		}
		CGImageDestinationAddImage(destination, thumbnail, nil)
		guard CGImageDestinationFinalize(destination) else { return nil }
		return (output as Data, PixelSize(width: width, height: height))
	}

	private static func rgba(_ color: NSColor) -> RGBAColor? {
		guard let srgb = color.usingColorSpace(.sRGB) else { return nil }
		return RGBAColor(
			red: srgb.redComponent,
			green: srgb.greenComponent,
			blue: srgb.blueComponent,
			alpha: srgb.alphaComponent
		)
	}

	private static func uniqued(_ types: [String]) -> [String] {
		var seen = Set<String>()
		return types.filter { seen.insert($0).inserted }
	}
}
